import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import test from 'node:test';
const { chromium } = createRequire(import.meta.url)('playwright');
const target = new URL(process.env.BROWSER_TEST_URL || 'http://127.0.0.1:4197');
if (!['localhost', '127.0.0.1'].includes(target.hostname)) throw new Error('Local fixtures only');
const base = target.origin;
for (const width of [1280, 816, 390]) test(`${width}px 社務待辦、搜尋、確認及分類導覽`, async t => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.BROWSER_EXECUTABLE});
  t.after(()=>browser.close());
  const context = await browser.newContext({viewport:{width,height:720}, serviceWorkers:'block'});
  const writes=[], errors=[], unknown=[];
  let fail=true;
  const activities=[{id:'pending',title:'待審活動',status:'pending_review',starts_at:'2030-01-01T01:00:00Z',ends_at:'2030-01-01T02:00:00Z',location:'合作社',registration_count:0,capacity:10,description:''},{id:'published',title:'已發布活動',status:'published',starts_at:'2030-01-01T01:00:00Z',ends_at:'2030-01-01T02:00:00Z',location:'合作社',registration_count:0,capacity:10,description:''}];
  await context.route('**/*',route=>{
    const req=route.request(), url=new URL(req.url()), path=url.pathname;
    if(url.origin!==base) return route.abort();
    if(!path.startsWith('/v1/')) return route.continue();
    if(path==='/v1/auth/refresh') return route.fulfill({json:{access_token:'isolated',user:{id:'admin',display_name:'測試管理員',email:'test@example.test',user_role:'admin'}}});
    if(path==='/v1/members/me') return route.fulfill({json:{membership_type:'member'}});
    if(req.method()==='POST' && path==='/v1/admin/activities/published/cancel') { writes.push(req.postDataJSON()); if(fail) return route.fulfill({status:409,json:{detail:'活動資料已更新，請重新核對'}}); activities[1].status='cancelled'; return route.fulfill({json:activities[1]}); }
    if(path==='/v1/admin/activities') return route.fulfill({json:activities});
    if(path==='/v1/admin/members') return route.fulfill({json:[{id:'m1',user_id:'u1',member_number:'M001',status:'active',share_count:1,share_capital_amount:1000},{id:'m2',user_id:'u2',member_number:'M002',status:'suspended',share_count:1,share_capital_amount:1000}]});
    if(path==='/v1/admin/member-roster') return route.fulfill({json:[{id:'r1',member_number:'M001',legal_name:'陳小明',email_masked:'c***',phone_masked:'09***',is_active:true,claimed:true,share_count:1,share_capital_amount:1000}]});
    if(['/v1/admin/member-proposals','/v1/admin/membership-applications','/v1/wishes','/v1/meetings'].includes(path)) return route.fulfill({json:[]});
    unknown.push(`${req.method()} ${path}`); return route.fulfill({status:404,json:{detail:'unknown fixture'}});
  });
  const page=await context.newPage();page.setDefaultTimeout(7000);page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${base}/admin/social`);
  await page.getByRole('heading',{name:'待審活動',exact:true}).waitFor();
  assert.equal(await page.getByRole('heading',{name:'已發布活動',exact:true}).count(),0);
  assert.equal(await page.getByRole('heading',{name:'M002',exact:true}).count(),0);
  await page.getByText('1 件待處理事項',{exact:true}).waitFor();
  const nav=page.getByRole('navigation',{name:'管理工作台分類'});
  assert.equal(await nav.locator('a.active').count(),1);
  assert.deepEqual(await nav.getByRole('link').allTextContents(),['訂餐營運','商品','會員社務','財務','設定']);
  if(width===1280) { const box=await page.getByRole('heading',{name:'待審活動',exact:true}).boundingBox();assert.ok(box.y<720,`待辦在第一屏: ${box.y}`); }
  await page.locator('.reading-menu > summary').click();await page.getByRole('button',{name:'放大',exact:true}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  if(process.env.BROWSER_SCREENSHOT_DIR) await page.screenshot({path:`${process.env.BROWSER_SCREENSHOT_DIR}/social-pending-${width}.png`,fullPage:true});
  await page.getByRole('button',{name:'全部',exact:true}).click();
  await page.getByRole('heading',{name:'已發布活動',exact:true}).waitFor();
  const card=page.locator('article').filter({has:page.getByRole('heading',{name:'已發布活動',exact:true})});
  await card.getByRole('button',{name:'取消活動',exact:true}).click();
  assert.equal(writes.length,0);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.equal(await card.getByRole('button',{name:'確認送出',exact:true}).isEnabled(),false);
  await card.getByRole('button',{name:'場地無法使用',exact:true}).click();
  await card.getByRole('button',{name:'返回',exact:true}).click(); assert.equal(writes.length,0);
  await card.getByRole('button',{name:'取消活動',exact:true}).click();
  await card.getByRole('button',{name:'主辦單位取消',exact:true}).click();
  await card.getByRole('button',{name:'確認送出',exact:true}).click();
  await card.getByText('活動資料已更新，請重新核對',{exact:true}).waitFor();
  assert.deepEqual(writes,[{reason:'主辦單位取消'}]);
  fail=false;
  await card.getByRole('button',{name:'取消活動',exact:true}).click();
  await card.getByRole('button',{name:'其他原因',exact:true}).click();
  await card.getByLabel('自訂處理原因',{exact:true}).fill('現場臨時停電');
  await card.getByRole('button',{name:'確認送出',exact:true}).click();
  await card.getByRole('status').filter({hasText:'處理完成'}).waitFor();
  assert.equal(writes.at(-1).reason,'現場臨時停電');
  await page.getByRole('tab',{name:'會籍管理',exact:true}).click();
  await page.getByRole('heading',{name:'陳小明 · M001',exact:true}).waitFor();
  await page.getByLabel('姓名、社員編號或會員識別碼',{exact:true}).fill('陳小明');
  assert.equal(await page.getByRole('heading',{name:'M002',exact:true}).count(),0);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.deepEqual(errors,[]);assert.deepEqual(unknown,[]);
});
